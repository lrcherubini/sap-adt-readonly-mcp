// The next SemVer version and its CHANGELOG entry, read from Conventional Commits.
//
// Pure functions: scripts/release.mjs reads git and writes the files; everything that decides
// lives here, so it is tested without a repository.
//
// The bump: a breaking change is major, `feat` is minor, `fix`, `perf` and `revert` are patch.
// While the major is 0 the public surface is not yet stable, so a breaking change is minor and
// nothing else moves the major. Other types (docs, test, refactor, chore, ...) are listed in the
// entry when a release happens, but alone they release nothing.

import { parseMessage } from './commit-lint.mjs';

const SEMVER = /^(\d+)\.(\d+)\.(\d+)$/;
const PATCH_TYPES = new Set(['fix', 'perf', 'revert']);
const OWN_SECTION = new Set(['feat', 'fix', 'perf']);

const SECTIONS = [
  ['breaking', 'Breaking changes'],
  ['feat', 'Features'],
  ['fix', 'Fixes'],
  ['perf', 'Performance'],
  ['other', 'Other changes'],
];

export const CHANGELOG_HEAD =
  '# Changelog\n\n' +
  'Generated by `npm run release` from Conventional Commits. The versioning policy is in the\n' +
  'README, under Contributing.\n';

/**
 * Where the commits of the next release start. Normally the latest tag. When package.json is
 * ahead of it -- a version was released (its `chore(release): vX.Y.Z` committed) and not tagged
 * yet -- the commits up to that release commit already belong to it, so the next one counts from
 * the release commit. `log` is the history since the tag, newest first, as {hash, subject}.
 * @returns {{base: string, by: 'tag' | 'release commit'}}
 */
export function releaseBase(tag, current, log) {
  if (tag === `v${current}`) return { base: tag, by: 'tag' };
  const hit = (log ?? []).find((c) => c.subject === `chore(release): v${current}`);
  return hit ? { base: hit.hash, by: 'release commit' } : { base: tag, by: 'tag' };
}

/** @returns {[number, number, number]} */
export function parseVersion(v) {
  const m = SEMVER.exec(String(v));
  if (!m) throw new Error(`"${v}" is not a MAJOR.MINOR.PATCH version`);
  return [Number(m[1]), Number(m[2]), Number(m[3])];
}

/**
 * @param {{hash: string, message: string}[]} commits newest first, as git log lists them
 * @returns {{breaking: object[], feat: object[], fix: object[], perf: object[], other: object[],
 *   skipped: object[]}} each entry `{hash, type, scope, subject}`; `skipped` holds the commits
 *   that are not Conventional Commits, or that git generated (merges)
 */
export function classify(commits) {
  const out = { breaking: [], feat: [], fix: [], perf: [], other: [], skipped: [] };
  for (const c of commits) {
    const p = parseMessage(c.message);
    if (p.type === null || p.generated) {
      out.skipped.push({ hash: c.hash, type: null, scope: null, subject: p.header });
      continue;
    }
    const item = { hash: c.hash, type: p.type, scope: p.scope, subject: p.subject };
    if (p.breaking) out.breaking.push(item);
    else if (OWN_SECTION.has(p.type)) out[p.type].push(item);
    else out.other.push(item);
  }
  return out;
}

/** @returns {{bump: 'major'|'minor'|'patch'|null, version: string|null}} */
export function nextVersion(current, groups) {
  const [major, minor, patch] = parseVersion(current);
  let bump = null;
  if (groups.breaking.length) bump = major === 0 ? 'minor' : 'major';
  else if (groups.feat.length) bump = 'minor';
  else if ([...groups.fix, ...groups.perf, ...groups.other].some((c) => PATCH_TYPES.has(c.type))) {
    bump = 'patch';
  }
  if (bump === 'major') return { bump, version: `${major + 1}.0.0` };
  if (bump === 'minor') return { bump, version: `${major}.${minor + 1}.0` };
  if (bump === 'patch') return { bump, version: `${major}.${minor}.${patch + 1}` };
  return { bump, version: null };
}

/** One `## [version] - date` section, LF line endings. */
export function renderEntry(version, date, groups) {
  const lines = [`## [${version}] - ${date}`];
  for (const [key, title] of SECTIONS) {
    if (!groups[key].length) continue;
    lines.push('', `### ${title}`, '');
    for (const c of groups[key]) {
      const scope = c.scope ? `**${c.scope}**: ` : '';
      const type = key === 'other' || key === 'breaking' ? `${c.type}: ` : '';
      lines.push(`- ${type}${scope}${c.subject} (${c.hash.slice(0, 7)})`);
    }
  }
  return lines.join('\n') + '\n';
}

const eolOf = (text) => (text.includes('\r\n') ? '\r\n' : '\n');
const withEol = (text, eol) => text.replace(/\r\n/g, '\n').replace(/\n/g, eol);

/** Puts the entry above the newest one, creating the file's head when there is none. */
export function prependEntry(changelog, entry) {
  const text = changelog ?? '';
  const eol = text ? eolOf(text) : '\n';
  const lf = text.replace(/\r\n/g, '\n');
  if (!lf.trim()) return withEol(`${CHANGELOG_HEAD}\n${entry}`, eol);
  const at = lf.search(/^## /m);
  const head = at < 0 ? lf.replace(/\n*$/, '\n\n') : lf.slice(0, at);
  const rest = at < 0 ? '' : `\n${lf.slice(at)}`;
  return withEol(`${head}${entry}${rest}`, eol);
}

/**
 * Sets `version` in package.json or package-lock.json text (the lockfile also carries it under
 * `packages[""]`). Formatting is npm's own: two-space JSON and a final newline.
 */
export function setVersion(jsonText, version) {
  parseVersion(version);
  const data = JSON.parse(jsonText);
  data.version = version;
  if (data.packages?.['']) data.packages[''].version = version;
  return withEol(JSON.stringify(data, null, 2) + '\n', eolOf(jsonText));
}
